import os
import re
from datetime import datetime


# =========================================================
# AI VIDEO EDITING ASSISTANT
# OFFLINE AI / RULE-BASED CONTENT GENERATION
# =========================================================


def clean_filename(filename):
    """
    Create a clean video name for AI processing.
    """

    if not filename:
        return "video"

    name = os.path.splitext(filename)[0]

    name = re.sub(r"[_\-]+", " ", name)

    name = re.sub(r"\s+", " ", name)

    return name.strip()


# =========================================================
# AI TITLE GENERATOR
# =========================================================

def generate_title(video_name="video"):

    name = clean_filename(video_name)

    title = f"{name.title()} - A Creative Video"

    return title


# =========================================================
# AI DESCRIPTION GENERATOR
# =========================================================

def generate_description(video_name="video"):

    name = clean_filename(video_name)

    description = (
        f"This video, '{name.title()}', was edited using "
        "the AI Video Editing Assistant. "
        "The application helps simplify video editing "
        "and prepares content for social media."
    )

    return description


# =========================================================
# AI HASHTAG GENERATOR
# =========================================================

def generate_hashtags(video_name="video"):

    name = clean_filename(video_name)

    words = name.lower().split()

    hashtags = [
        "#AI",
        "#VideoEditing",
        "#ContentCreator",
        "#VideoEditor",
        "#SocialMedia"
    ]

    for word in words:

        if len(word) > 2:

            tag = "#" + re.sub(
                r"[^a-zA-Z0-9]",
                "",
                word
            )

            if tag not in hashtags:

                hashtags.append(tag)

    return " ".join(hashtags)


# =========================================================
# AI CAPTION GENERATOR
# =========================================================

def generate_caption(video_name="video"):

    name = clean_filename(video_name)

    caption = (
        f"Creating and editing '{name.title()}' "
        "with the help of an AI-powered video editing assistant."
    )

    return caption


# =========================================================
# TRANSCRIPT GENERATOR
# =========================================================

def generate_transcript(video_name="video"):

    name = clean_filename(video_name)

    transcript = (
        "Transcript generated by the offline AI module.\n\n"
        f"Video: {name.title()}\n\n"
        "This is a demonstration transcript generated "
        "from available video information. "
        "For full speech-to-text transcription, "
        "a speech recognition model can be integrated."
    )

    return transcript


# =========================================================
# SUMMARY GENERATOR
# =========================================================

def generate_summary(video_name="video"):

    name = clean_filename(video_name)

    summary = (
        f"Summary for '{name.title()}':\n\n"
        "The video can be processed using the editing "
        "features of the application. Users can trim, "
        "split, merge, filter and add audio before exporting "
        "the final video."
    )

    return summary


# =========================================================
# TRANSLATION
# =========================================================

def translate_text(text, language="English"):

    if not text:

        return ""

    if language.lower() == "english":

        return text

    # Offline demonstration translation layer.
    # Additional language models can be integrated later.

    return (
        f"[Translated to {language}]\n\n"
        f"{text}"
    )


# =========================================================
# VIDEO CONTENT SUGGESTIONS
# =========================================================

def generate_suggestions(video_name="video"):

    suggestions = [

        "Keep the most important content near the beginning.",

        "Remove unnecessary or repetitive sections.",

        "Use background music at a suitable volume.",

        "Apply filters only when they improve visual quality.",

        "Add captions to make the video easier to understand.",

        "Use an engaging title and relevant hashtags.",

        "Review the final timeline before exporting.",

        "Choose an appropriate video format for the target platform."

    ]

    return suggestions


# =========================================================
# AI CONTENT GENERATOR
# =========================================================

def generate_all_content(video_name="video"):

    return {

        "title":
            generate_title(video_name),

        "description":
            generate_description(video_name),

        "hashtags":
            generate_hashtags(video_name),

        "caption":
            generate_caption(video_name),

        "transcript":
            generate_transcript(video_name),

        "summary":
            generate_summary(video_name),

        "suggestions":
            generate_suggestions(video_name),

        "generated_at":
            datetime.now().isoformat()

    }


# =========================================================
# AI REQUEST HANDLER
# =========================================================

def process_ai_request(
    request_type,
    video_name="video",
    text="",
    language="English"
):

    if request_type == "title":

        return generate_title(video_name)


    if request_type == "description":

        return generate_description(video_name)


    if request_type == "hashtags":

        return generate_hashtags(video_name)


    if request_type == "caption":

        return generate_caption(video_name)


    if request_type == "transcript":

        return generate_transcript(video_name)


    if request_type == "summary":

        return generate_summary(video_name)


    if request_type == "translate":

        return translate_text(
            text,
            language
        )


    if request_type == "suggestions":

        return generate_suggestions(
            video_name
        )


    if request_type == "all":

        return generate_all_content(
            video_name
        )


    return {
        "error": "Unknown AI request type"
    }